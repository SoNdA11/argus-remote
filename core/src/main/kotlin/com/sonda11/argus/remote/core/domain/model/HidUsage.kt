package com.sonda11.argus.remote.core.domain.model

/**
 * USB HID keyboard usage identifiers used by the presentation deck.
 */
object HidUsage {
    const val RIGHT_ARROW = 0x4F
    const val LEFT_ARROW = 0x50
    const val PAGE_UP = 0x4B
    const val PAGE_DOWN = 0x4E
    const val SPACE = 0x2C
    const val ESCAPE = 0x29
    const val KEY_B = 0x05
    const val KEY_F = 0x09
    const val KEY_T = 0x17
}
